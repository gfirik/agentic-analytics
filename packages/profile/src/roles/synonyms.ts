/** The normalized phrases of a role (tokens joined by one space). */
export const SYNONYMS: ReadonlyMap<Role, readonly string[]> = new Map(
  (Object.entries(LIST) as [Role, readonly string[]][]).map(([role, phrases]) => [
    role,
    [...phrases, ...(UZ_CYRILLIC[role] ?? [])].map((p) => headerTokens(p).join(" ")),
  ]),
);

