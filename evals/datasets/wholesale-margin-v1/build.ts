// Regenerates wholesale-margin-v1/files/ and expectations.yaml deterministically.
// Run: bun run --filter @agentic-analytics/eval-datasets build:wholesale-margin
import { createHash } from "node:crypto";
import { mkdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { stringify } from "yaml";
import { wholesaleMarginExpectations, wholesaleMarginFiles } from "../src/index.ts";

const dir = import.meta.dirname;
mkdirSync(join(dir, "files"), { recursive: true });
for (const [name, data] of Object.entries(wholesaleMarginFiles())) {
  writeFileSync(join(dir, "files", name), data);
  process.stdout.write(`${name}  ${data.length} bytes  sha256=${createHash("sha256").update(data).digest("hex")}\n`);
}
const header =
  "# Expected figures for wholesale-margin-v1 (README.md explains them). Generated by build.ts from the invoice lines with\n# the formulas of docs/specs/analysis-library.md section 9 and 10; a test re-derives every figure independently.\n";
writeFileSync(join(dir, "expectations.yaml"), header + stringify(wholesaleMarginExpectations(), { lineWidth: 0 }));
