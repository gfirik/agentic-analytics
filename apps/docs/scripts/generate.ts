// Generates the docs pages and data that must not drift from the product (docs/DOCS-SITE.md §4): it runs the real
// engine on examples/coffee-roaster with the scripted model (no LLM, offline embedder) and records its events,
// draft and verified report and a real retrieval trace for the islands; it renders the HTTP API reference from the
// server's own OpenAPI spec, the report schema from its JSON Schema, and copies the eval results and project docs.
// Runs before every build (`bun run build`); everything it writes is gitignored.
import { mkdirSync, mkdtempSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { JobManager, runJob } from "@agentic-analytics/core";
import { coffeePlanner } from "@agentic-analytics/core/testing";
import { coffeeRoasterFiles } from "@agentic-analytics/eval-datasets";
import { type DatasetScore, type RealSuiteResult, summarize } from "@agentic-analytics/eval-runner";
import { hashEmbedder, searchDocuments } from "@agentic-analytics/retrieval";
import type { JobEvent, Report } from "@agentic-analytics/schema";
import { createApp } from "@agentic-analytics/server";
import { sql, Workspace } from "@agentic-analytics/store";

const DOCS = join(import.meta.dirname, "..");
const ROOT = join(DOCS, "..", "..");
const CONTENT = join(DOCS, "src", "content", "docs");
const DATA = join(DOCS, "src", "data");
mkdirSync(DATA, { recursive: true });

const page = (title: string, description: string, body: string) =>
  `---\ntitle: ${JSON.stringify(title)}\ndescription: ${JSON.stringify(description)}\n---\n\n<!-- Generated by apps/docs/scripts/generate.ts. Do not edit. -->\n\n${body.trim()}\n`;
const write = (rel: string, text: string) => {
  mkdirSync(join(CONTENT, rel, ".."), { recursive: true });
  writeFileSync(join(CONTENT, rel), text);
};

// 1. A real run on the example, for the CitationDemo, Decomposition and VerifierDiff islands. (The Pipeline island
//    plays the README GIF's checked-in data instead: scripts/pipeline-data.ts.)
const dir = mkdtempSync(join(tmpdir(), "aa-docs-"));
let coffeeReport: Report | undefined;
try {
  const events: JobEvent[] = [];
  const files = Object.entries(coffeeRoasterFiles()).map(([name, bytes]) => ({ name, bytes }));
  const out = await runJob(
    { dir, jobId: "coffee-demo", files, options: { today: "2026-07-01", currency: "USD" } },
    { model: coffeePlanner(), embedder: hashEmbedder(), onEvent: (e) => events.push(e), now: () => new Date("2026-07-01T09:00:00Z") },
  );
  writeFileSync(join(DATA, "coffee.json"), JSON.stringify({ events, draft: out.draft, report: out.report }));
  coffeeReport = out.report;

  // 2. A real retrieval trace (BM25 rank, vector rank, fused score) for the RagStepper.
  const ws = await Workspace.open(join(dir, "job.duckdb"));
  try {
    const query = "why did the hotel stop its wholesale order";
    const r = await searchDocuments(ws, query, { embedder: hashEmbedder(), k: 6 });
    // What the quarantined extractor returned for the top chunk in the run itself.
    const extract = await ws.one<{ payload: string }>(
      sql`SELECT payload::VARCHAR AS payload FROM extracts WHERE chunk_id = ${r.hits[0]?.chunk_id ?? ""} AND NOT suspicious LIMIT 1`,
    );
    writeFileSync(
      join(DATA, "rag.json"),
      JSON.stringify({
        query,
        degraded: r.degraded,
        extract: extract ? (JSON.parse(extract.payload) as unknown) : null,
        hits: r.hits.map((h) => ({
          chunk: h.chunk_id,
          file: h.file,
          heading: h.heading_path.join(" › "),
          text: h.text.slice(0, 220),
          bm25: h.bm25_rank ?? null,
          vector: h.vector_rank ?? null,
          score: h.score,
        })),
      }),
    );
  } finally {
    ws.close();
  }
} finally {
  rmSync(dir, { recursive: true, force: true });
}

// 3. The HTTP API reference, from the server's own OpenAPI spec.
const jobs = mkdtempSync(join(tmpdir(), "aa-docs-api-"));
try {
  const app = createApp(
    new JobManager({ root: jobs, model: coffeePlanner(), deps: () => ({ model: coffeePlanner(), embedder: hashEmbedder() }) }),
  );
  const spec = (await (await app.request("/openapi.json")).json()) as {
    paths: Record<string, Record<string, { summary?: string; responses?: Record<string, { description?: string }> }>>;
  };
  mkdirSync(join(DOCS, "public"), { recursive: true });
  writeFileSync(join(DOCS, "public", "openapi.json"), JSON.stringify(spec, null, 2));
  const rows = Object.entries(spec.paths).flatMap(([path, ops]) =>
    Object.entries(ops).map(
      ([method, op]) =>
        `| \`${method.toUpperCase()}\` | \`${path}\` | ${op.summary ?? ""} | ${Object.keys(op.responses ?? {}).join(", ")} |`,
    ),
  );
  write(
    "use-it/http-api.md",
    page(
      "HTTP API",
      "Every endpoint of `aa serve`, generated from the server's OpenAPI spec.",
      `Start it with \`aa serve\` (default \`http://127.0.0.1:8080\`). The spec below is generated from the same Zod schemas that validate requests; fetch it live at \`/openapi.json\`.

| Method | Path | Does | Responses |
|---|---|---|---|
${rows.join("\n")}

## Example

\`\`\`bash
curl -F 'files[]=@examples/coffee-roaster/sales-2026.xlsx' -F 'files[]=@examples/coffee-roaster/email-0412.eml' \\
  -F 'options={"currency":"USD"}' http://127.0.0.1:8080/v1/jobs
curl -N http://127.0.0.1:8080/v1/jobs/<job_id>/events      # live progress (SSE)
curl http://127.0.0.1:8080/v1/jobs/<job_id>/report?format=html > report.html
\`\`\`

## Security

- The API listens on 127.0.0.1 and answers only localhost host names (plus \`--host\` and \`AA_ALLOWED_HOSTS\`): a request whose \`Host\` or \`Origin\` names another host gets 403, so a web page can't reach it through DNS rebinding.
- \`API_TOKEN\` turns on bearer auth for \`/v1/jobs*\` and \`/mcp\`; without the token, \`/v1/health\` reports only the engine and DuckDB. \`aa serve\` refuses a non-loopback address without \`API_TOKEN\` (opt out with \`--allow-no-auth\` / \`AA_ALLOW_NO_AUTH=1\` behind a proxy or a localhost-only port mapping). CORS is off.
- An unexpected error is a 500 with a generic message; the details go to the server log.

The full OpenAPI document, regenerated on every docs build: [openapi.json](/agentic-analytics/openapi.json).`,
    ),
  );
} finally {
  rmSync(jobs, { recursive: true, force: true });
}

// 4. The report schema, from its JSON Schema.
const schema = JSON.parse(readFileSync(join(ROOT, "packages/schema/json/report.schema.json"), "utf8")) as {
  properties?: Record<string, { description?: string; type?: string }>;
  required?: string[];
};
const props = Object.entries(schema.properties ?? {}).map(
  ([k, v]) =>
    `| \`${k}\` | ${(schema.required ?? []).includes(k) ? "yes" : "no"} | ${v.type ?? "object"} | ${(v.description ?? "").replace(/\|/g, "\\|")} |`,
);
write(
  "reference/report-schema.md",
  page(
    "Report schema",
    "report.json v1, generated from the JSON Schema that the engine validates every report against.",
    `Every report the engine ships validates against this schema (\`packages/schema/json/report.schema.json\`, generated from Zod and checked for drift in CI). Numbers in text are \`{{N…}}\` placeholders that resolve to facts; every fact carries its computation (SQL with parameters, or a function and its inputs) and citations; every claim carries citations and a causal grade.

| Field | Required | Type | Notes |
|---|---|---|---|
${props.join("\n")}

The complete schema: [report.schema.json](https://github.com/gfirik/agentic-analytics/blob/main/packages/schema/json/report.schema.json). The fixture \`packages/schema/test/fixtures/report.coffee-roaster.json\` is a full example.`,
  ),
);

// 5. Eval results and project docs, copied as they are.
const strip = (md: string) => md.replace(/^# .*\n+/, "");
write(
  "quality/results.md",
  page("Eval results", "The latest results per model, from evals/RESULTS.md.", strip(readFileSync(join(ROOT, "evals/RESULTS.md"), "utf8"))),
);
for (const [file, rel, title, description] of [
  ["docs/DECISIONS.md", "project/decisions.md", "Decisions", "Every architecture decision and why it was made."],
  ["docs/ROADMAP.md", "project/roadmap.md", "Roadmap", "Milestones, acceptance criteria and what comes after v0.1."],
  ["CHANGELOG.md", "project/changelog.md", "Changelog", "What changed in each release."],
] as const)
  write(rel, page(title, description, strip(readFileSync(join(ROOT, file), "utf8"))));

// 6. The shared diagrams (the same files the README and ARCHITECTURE.md embed).
for (const d of ["architecture", "pipeline"])
  writeFileSync(join(DATA, `${d}.mmd`), readFileSync(join(ROOT, "docs/assets/diagrams", `${d}.mmd`), "utf8"));

// 7. The landing page's report (src/pages/index.astro): the first finding of the same real run, every fact its claims
//    and its top recommendation use, and the facts those are computed from (so each chip opens a fact whose inputs
//    open too). Values are the facts' stored values; the page only formats them.
if (!coffeeReport) throw new Error("docs: the coffee-roaster run produced no report");
{
  const report = coffeeReport;
  const byId = new Map(report.facts.map((f) => [f.id, f]));
  const file = (id: string) => report.sources.find((s) => s.id === id)?.file ?? id;
  const finding = report.findings[0];
  const rec = report.recommendations[0];
  if (!finding || !rec) throw new Error("docs: the coffee-roaster report has no finding or recommendation");
  const direct = [
    ...finding.claims.flatMap((c) => c.facts),
    ...[rec.impact?.low, rec.impact?.high].filter((x): x is string => typeof x === "string"),
  ].filter((id, i, a) => a.indexOf(id) === i);
  const closure = new Set<string>();
  const visit = (id: string) => {
    if (closure.has(id)) return;
    const f = byId.get(id);
    if (!f) throw new Error(`docs: unknown fact ${id} in the landing finding`);
    closure.add(id);
    if (f.computation.kind === "function") for (const input of f.computation.inputs ?? []) visit(input);
  };
  for (const id of direct) visit(id);
  const facts = Object.fromEntries(
    [...closure].map((id) => {
      const f = byId.get(id) as (typeof report.facts)[number];
      return [
        id,
        {
          id,
          label: f.label,
          value: f.value,
          unit: f.unit,
          currency: f.currency ?? null,
          verified: f.verified ?? false,
          computation: f.computation,
          citations: f.citations.map((c) => ({
            source_id: c.source_id,
            file: file(c.source_id),
            rows: (c.rows ?? []).slice(0, 12),
            count: c.rows?.length ?? 0,
          })),
        },
      ];
    }),
  );
  const v = report.verification;
  writeFileSync(
    join(DATA, "landing.json"),
    JSON.stringify({
      run: { example: "examples/coffee-roaster", model: "scripted planner, no LLM", today: "2026-07-01" },
      finding: {
        id: finding.id,
        type: finding.type,
        severity: finding.severity,
        title: finding.title,
        method: finding.method ?? null,
        confidence: finding.confidence,
        claims: finding.claims.map((c) => ({
          text: c.text,
          facts: c.facts,
          grade: c.causal_grade,
          verified: c.verified ?? false,
          citations: c.citations.map((x) => ({ source_id: x.source_id, file: file(x.source_id), quote: x.quote ?? null })),
        })),
      },
      recommendation: {
        id: rec.id,
        action: rec.action,
        low: rec.impact?.low ?? null,
        high: rec.impact?.high ?? null,
        horizon: rec.impact?.horizon ?? null,
        confidence: rec.confidence,
        not_advised: rec.not_advised ?? null,
      },
      direct,
      facts,
      verification: {
        numbers_checked: v.numbers_checked,
        numbers_mismatched: v.numbers_mismatched,
        rederived_metrics: v.rederived_metrics,
        rederivation_mismatches: v.rederivation_mismatches,
        citations_checked: v.citations_checked,
        citations_unsupported: v.citations_unsupported,
        claims_dropped: v.claims_dropped.length,
        claims_downgraded: v.claims_downgraded.length,
      },
    }),
  );
}

// 8. The landing page's eval numbers, from the committed results files (evals/results/*.json): the suite metrics are
//    computed by the eval runner's own summarize(), the same function that writes evals/RESULTS.md.
{
  const RESULTS = join(ROOT, "evals", "results");
  const latest = (suffix: string) => {
    const name = readdirSync(RESULTS)
      .filter((f) => f.endsWith(suffix))
      .sort()
      .at(-1);
    if (!name) throw new Error(`docs: no evals/results/*${suffix}`);
    return { name, data: JSON.parse(readFileSync(join(RESULTS, name), "utf8")) as unknown };
  };
  type SuiteFile = { suite: string; model: string; note?: string; date: string; datasets: number; scores: DatasetScore[] };
  const suite = (suffix: string) => {
    const { name, data } = latest(suffix);
    const s = data as SuiteFile;
    return {
      file: `evals/results/${name}`,
      suite: s.suite,
      model: s.model,
      note: s.note ?? null,
      date: s.date,
      datasets: s.scores.length,
      completed: s.scores.filter((x) => x.completed).length,
      bars: summarize(s.scores),
    };
  };
  const real = latest("-baseline-real.json");
  const r = real.data as RealSuiteResult;
  writeFileSync(
    join(DATA, "evals.json"),
    JSON.stringify({
      synthetic: suite("-baseline-full.json"),
      smoke: suite("-configured-small-smoke.json"),
      full: suite("-configured-small-full.json"),
      real: {
        file: `evals/results/${real.name}`,
        model: r.model,
        note: r.note ?? null,
        date: r.date,
        datasets: r.datasets.map((d) => ({
          dataset: d.dataset,
          title: d.title,
          publisher: d.publisher,
          licence: d.licence,
          page: d.page,
          completed: d.completed,
          seconds: d.seconds,
          checks: d.checks.map((c) => ({ id: c.id, about: c.about, pass: c.pass, detail: c.detail })),
        })),
      },
    }),
  );
}

process.stdout.write("docs: generated data and reference pages\n");
