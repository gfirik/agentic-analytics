// Builds the standalone `aa` CLI binary for the machine it runs on (`bun build --compile`), with DuckDB's shared
// library embedded (apps/cli/src/native-lib.ts explains why), and writes a SHA256 checksum next to it.
// The release workflow runs it on one native runner per target, because each platform's DuckDB bindings are an
// optional dependency that only installs on that platform. Run with Bun: `bun scripts/build-binary.ts`.
//
// Output: dist/bin/aa-<os>-<arch>[.exe] and dist/bin/aa-<os>-<arch>[.exe].sha256 (`sha256sum -c` format).
import { spawnSync } from "node:child_process";
import { createHash } from "node:crypto";
import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { basename, dirname, join } from "node:path";

const root = join(import.meta.dirname, "..");
const os = process.platform === "win32" ? "windows" : process.platform === "darwin" ? "macos" : process.platform;
const arch = process.arch;
const binding = `${process.platform}-${arch}`;
const LIB: Record<string, string> = { linux: "libduckdb.so", darwin: "libduckdb.dylib", win32: "duckdb.dll" };
const lib = LIB[process.platform];
if (!lib) throw new Error(`no standalone binary for ${process.platform}`);

// The bindings package for this platform, resolved from the store package that depends on @duckdb/node-api.
const req = createRequire(join(root, "packages", "store", "package.json"));
const api = dirname(req.resolve("@duckdb/node-api/package.json"));
const bindings = dirname(createRequire(join(api, "package.json")).resolve("@duckdb/node-bindings/package.json"));
const native = dirname(createRequire(join(bindings, "package.json")).resolve(`@duckdb/node-bindings-${binding}/package.json`));
const version = (JSON.parse(readFileSync(join(api, "package.json"), "utf8")) as { version: string }).version;

// Staged into a gitignored folder: the library, and the binary's entry that loads it before the CLI.
const stage = join(root, "apps", "cli", "native");
mkdirSync(stage, { recursive: true });
copyFileSync(join(native, lib), join(stage, lib));
writeFileSync(
  join(stage, "entry.ts"),
  `// Generated by scripts/build-binary.ts: the standalone binary's entry. Not part of the Node CLI.
import { dlopen, FFIType } from "bun:ffi";
import { stageNativeLib } from "../src/native-lib.ts";
// @ts-expect-error a file embedded by bun build --compile
import embedded from "./${lib}" with { type: "file" };

const path = await stageNativeLib({
  embedded,
  name: ${JSON.stringify(lib)},
  version: ${JSON.stringify(version)},
  read: async (p) => new Uint8Array(await Bun.file(p).arrayBuffer()),
  size: (p) => Bun.file(p).size,
});
dlopen(path, { duckdb_library_version: { args: [], returns: FFIType.cstring } });
process.env.AA_STANDALONE = "1";
await import("../src/main.ts");
`,
);

const out = join(root, "dist", "bin", `aa-${os}-${arch}${process.platform === "win32" ? ".exe" : ""}`);
mkdirSync(dirname(out), { recursive: true });
// The other platforms' bindings are never installed here; their require() calls stay unresolved in the bundle.
const others = ["linux-x64", "linux-arm64", "linux-x64-musl", "linux-arm64-musl", "darwin-x64", "darwin-arm64", "win32-x64", "win32-arm64"]
  .filter((b) => b !== binding)
  .flatMap((b) => ["--external", `@duckdb/node-bindings-${b}/duckdb.node`]);
// This script runs on Bun, so its own executable is the bundler; no shell, so paths with spaces stay one argument.
const r = spawnSync(process.execPath, ["build", "--compile", "--minify", join(stage, "entry.ts"), ...others, "--outfile", out], {
  cwd: root,
  stdio: "inherit",
});
if (r.status !== 0) process.exit(r.status ?? 1);

const sum = createHash("sha256").update(readFileSync(out)).digest("hex");
writeFileSync(`${out}.sha256`, `${sum}  ${basename(out)}\n`);
process.stdout.write(`built ${out} (${(readFileSync(out).length / 1e6).toFixed(1)} MB), sha256 ${sum}\n`);
